/** P1 diagnostic of unchanged inputs; asserts independent statement bridges, not new forecasts. */
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import type { FinancialResult, ForecastRecord } from '../contracts/contracts.ts';
import { CompanyInputSchema, DeterministicRequestSchema, SimulationResultSchema } from '../src/lib/server/schemas.ts';
import { simulate_deterministic } from '../src/lib/server/engine/scenarios.ts';

const read = (path: string) => JSON.parse(readFileSync(path, 'utf8'));
const company = CompanyInputSchema.parse(read('data/synthetic_hvac_company.json'));
const request = DeterministicRequestSchema.parse(read('contracts/example-request.json'));
const operational = read('data/example-operational-trace.json');
const original = JSON.stringify({ company, request });
const result = simulate_deterministic(company, request, 'p1-unchanged-financial-investigation');
const reference = SimulationResultSchema.parse(read('contracts/example-result.json'));
assert.deepEqual(result.scenarios, reference.scenarios);
assert.deepEqual(result.comparisons, reference.comparisons);
assert.equal(result.input_fingerprint, operational.input_fingerprint);
assert.equal(JSON.stringify({ company, request }), original);
const close = (a: number, b: number) => assert.ok(Math.abs(a - b) < 1e-6, `${a} != ${b}`);
const selected = [0, 1, 2, 3, 5, 12, 13, 24, 60];
const summaries: Record<string, unknown> = {};
const monthly: Record<string, unknown[]> = {};
const usd = (v: number) => v.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
let markdown = '# Unchanged example: P1 financial reconciliation\n\nGenerated by `node scripts/reconcile_example_financials.ts`. Same input fingerprint as P2 operational trace; all paths/comparisons exactly reproduce the frozen reference. Values below are scenario minus baseline, USD. Month 0 has stock balances only; flow columns show —. No fixture, policy or forecast value was changed.\n\n';
for (const [id, path] of Object.entries(result.scenarios)) {
  const base = result.scenarios.baseline;
  const rows = path.months.slice(1) as ForecastRecord[];
  const bases = base.months.slice(1) as ForecastRecord[];
  const delta = (i: number, field: keyof FinancialResult) => Number(rows[i].financials[field]) - Number(bases[i].financials[field]);
  const total = (field: keyof FinancialResult) => rows.reduce((sum, _, i) => sum + delta(i, field), 0);
  let cumulativeUfcf = 0, cashBridge = 0;
  const details = rows.map((row, i) => {
    const f = row.financials, b = bases[i].financials;
    const trace = operational.trace[id][i + 1];
    close(trace.total_revenue_usd, f.revenue); close(trace.cash_end_usd, f.cash_end);
    close(trace.debt_end_usd, f.debt_end); close(trace.ebitda_delta_usd, f.ebitda - b.ebitda);
    close(f.revenue, row.operations.completed_jobs * row.operations.average_ticket + f.other_revenue);
    close(f.ebitda, f.revenue - f.service_variable_cost - f.tech_direct_labor - f.vehicle_direct_opex
      - f.other_direct_cost - f.fixed_overhead - f.incremental_marketing - f.recruitment);
    close(f.cash_taxes, Math.max(0, f.ebitda - f.depreciation - f.cash_interest) * company.global_assumptions.tax_rate);
    close(f.cash_change, f.ebitda - f.cash_interest - f.cash_taxes - f.delta_nwc
      - f.capex + f.new_borrowings - f.debt_principal);
    close(f.cash_end, path.months[i].financials.cash_end + f.cash_change);
    close(f.debt_end, path.months[i].financials.debt_end + f.new_borrowings - f.debt_principal);
    close(delta(i, 'fixed_overhead'), 0); close(delta(i, 'other_direct_cost'), 0);
    close(delta(i, 'other_revenue'), 0); close(delta(i, 'maintenance_capex'), 0);
    if (id !== 'baseline') {
      const month = i + 1;
      close(delta(i, 'growth_capex'), month === 1 ? 120000 : 0);
      close(delta(i, 'new_borrowings'), month === 1 ? 60000 : 0);
      close(delta(i, 'debt_principal'), month >= 2 && month <= 49 ? 1250 : 0);
      close(delta(i, 'cash_interest'), month >= 2 && month <= 49 ? (60000 - (month - 2) * 1250) * .08 / 12 : 0);
    }
    close(f.unlevered_fcf, f.ebitda - f.unlevered_tax - f.delta_nwc - f.capex);
    cumulativeUfcf += delta(i, 'unlevered_fcf');
    cashBridge += delta(i, 'ebitda') - delta(i, 'cash_interest') - delta(i, 'cash_taxes')
      - delta(i, 'delta_nwc') - delta(i, 'capex') + delta(i, 'new_borrowings') - delta(i, 'debt_principal');
    close(cashBridge, f.cash_end - b.cash_end);
    if (id !== 'baseline') close(cumulativeUfcf, result.comparisons[id].monthly_deltas[i + 1].cumulative_incremental_unlevered_fcf);
    if (row.valuation.status === 'meaningful') close(row.valuation.equity_value!,
      row.valuation.ttm_ebitda * request.exit_multiple - f.debt_end + f.cash_end);
    return { month: i + 1, revenue_delta: delta(i, 'revenue'), variable_cost_delta: delta(i, 'service_variable_cost'),
      payroll_delta: delta(i, 'tech_direct_labor'), fleet_cost_delta: delta(i, 'vehicle_direct_opex'),
      marketing_delta: delta(i, 'incremental_marketing'), recruitment_delta: delta(i, 'recruitment'),
      ebitda_delta: delta(i, 'ebitda'), depreciation_delta: delta(i, 'depreciation'),
      interest_delta: delta(i, 'cash_interest'), cash_tax_delta: delta(i, 'cash_taxes'), nwc_change_delta: delta(i, 'delta_nwc'),
      capex_delta: delta(i, 'capex'), borrowings_delta: delta(i, 'new_borrowings'), principal_delta: delta(i, 'debt_principal'),
      cash_delta: f.cash_end - b.cash_end, debt_delta: f.debt_end - b.debt_end,
      cumulative_incremental_ufcf: cumulativeUfcf };
  });
  monthly[id] = [{ month: 0, cash_delta: 0, debt_delta: 0 }, ...details];
  const totals = Object.fromEntries(['revenue','service_variable_cost','tech_direct_labor','vehicle_direct_opex',
    'incremental_marketing','recruitment','ebitda','depreciation','cash_interest','cash_taxes','delta_nwc',
    'capex','new_borrowings','debt_principal','unlevered_tax','unlevered_fcf'].map(field => [field, total(field as keyof FinancialResult)]));
  close(totals.ebitda, totals.revenue - totals.service_variable_cost - totals.tech_direct_labor
    - totals.vehicle_direct_opex - totals.incremental_marketing - totals.recruitment);
  close(totals.delta_nwc, (rows[59].financials.nwc_end - bases[59].financials.nwc_end));
  const terminal = rows[59], baseTerminal = bases[59];
  const terminalTtmDelta = terminal.valuation.ttm_ebitda - baseTerminal.valuation.ttm_ebitda;
  const equityDelta = terminal.valuation.equity_value! - baseTerminal.valuation.equity_value!;
  close(equityDelta, terminalTtmDelta * request.exit_multiple - details[59].debt_delta + details[59].cash_delta);
  if (id !== 'baseline') {
    assert.equal(path.metrics.payback.status, 'not_reached');
    assert.equal(path.metrics.payback.first_investment_month, 1);
    assert.ok(details.every(row => row.cumulative_incremental_ufcf < -1e-6));
  }
  summaries[id] = { totals, ending_cash_delta: details[59].cash_delta, ending_debt_delta: details[59].debt_delta,
    terminal_ttm_ebitda_delta: terminalTtmDelta, terminal_enterprise_value_delta: terminalTtmDelta * request.exit_multiple,
    terminal_equity_delta: equityDelta, payback: path.metrics.payback,
    growth_purchase_months: rows.filter(r => r.financials.growth_capex > 0).map(r => r.month),
    new_borrowing_months: rows.filter(r => r.financials.new_borrowings > 0).map(r => r.month),
    revenue_benefit_months: details.filter(r => r.revenue_delta > 1e-7).map(r => r.month) };
  markdown += `## ${id}\n\n| Month | Revenue Δ | EBITDA Δ | CapEx Δ | Borrowing Δ | Cash Δ | Debt Δ | Cumulative project cash flow Δ |\n|---|---|---|---|---|---|---|---|\n| 0 | — | — | — | — | 0.00 | 0.00 | — |\n`;
  for (const d of details.filter(d => selected.includes(d.month))) markdown += `| ${d.month} | ${usd(d.revenue_delta)} | ${usd(d.ebitda_delta)} | ${usd(d.capex_delta)} | ${usd(d.borrowings_delta)} | ${usd(d.cash_delta)} | ${usd(d.debt_delta)} | ${usd(d.cumulative_incremental_ufcf)} |\n`;
  markdown += '\n';
}
writeFileSync('data/example-financial-reconciliation.json', JSON.stringify({ reviewed_dependency: '51a89cf',
  input_fingerprint: result.input_fingerprint, operational_trace_commit: '51a89cf', selected_months: selected, summaries, monthly }, null, 2) + '\n');
writeFileSync('docs/EXAMPLE_FINANCIAL_TRACE.md', markdown);
console.log(JSON.stringify(summaries, null, 2));
