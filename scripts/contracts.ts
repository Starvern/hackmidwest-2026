import { readFileSync, writeFileSync } from 'node:fs';
import { z } from 'zod';
import * as runtime from '../src/lib/server/schemas.ts';

const check = process.argv.includes('--check');
const entries = Object.entries(runtime).filter(([name, value]) => name.endsWith('Schema') && value instanceof z.ZodType)
  .sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
function artifact(path: string, contents: string) {
  if (check) {
    if (readFileSync(path, 'utf8') !== contents) throw new Error(`Contract drift: regenerate ${path} with npm run contracts:generate`);
  } else writeFileSync(path, contents);
}
const aliases = entries.map(([name]) => `export type ${name.slice(0, -6)} = z.infer<typeof Runtime.${name}>;`).join('\n');
artifact('contracts/contracts.ts', `/** Generated by npm run contracts:generate. Edit authoritative Zod schemas instead. */\nimport type { z } from 'zod';\nimport type * as Runtime from '../src/lib/server/schemas.ts';\n\n${aliases}\n`);
const all = Object.fromEntries(entries.map(([name, schema]) => [name.slice(0, -6), z.toJSONSchema(schema as z.ZodType, { target: 'draft-2020-12' })]));
artifact('contracts/schemas.json', JSON.stringify(all, null, 2) + '\n');
for (const [name, filename] of [
  ['CompanyInput', 'company'], ['ScenarioInput', 'scenario'], ['DeterministicRequest', 'deterministic-request'],
  ['MonteCarloRequest', 'monte-carlo-request'], ['SimulationResult', 'simulation-result'],
] as const) artifact(`contracts/${filename}.schema.json`, JSON.stringify(all[name], null, 2) + '\n');
console.log(check ? 'Contract artifacts match authoritative schemas' : 'Generated contract artifacts');
